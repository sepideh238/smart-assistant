/*
========================================
1️⃣ وارد کردن استایل کامپوننت
========================================
فایل SCSS مربوط به کارت محصول را
اینجا وارد می‌کنیم تا استایل‌ها
روی این کامپوننت اعمال شوند.
*/
import "./ProductCard.scss";

/*
========================================
2️⃣ تعریف کامپوننت ProductCard
========================================
این کامپوننت وظیفه نمایش یک کارت
محصول را دارد.

در این مرحله:
- هنوز props نداریم
- هنوز دیتا داینامیک نداریم
- فقط UI ساخته می‌شود
*/
export default function ProductCard({ product }) {
  // فرض می‌کنیم prop به نام product دریافت می‌شود که شامل اطلاعات محصول است

  // مقادیر پیش‌فرض در صورت عدم وجود prop
  const defaultProduct = {
    imageUrl: "/images/product-placeholder.png",
    title: "Apple iPad Pro 11",
    price: "25,000,000 T",
    // اگر بخواهید لینک به صفحه جزئیات محصول داشته باشید، می‌توانید id یا slug را هم اضافه کنید
    // id: 'some-product-id'
  };

  // استفاده از مقادیر prop یا مقادیر پیش‌فرض
  const imageUrl = product?.imageUrl || defaultProduct.imageUrl;
  const title = product?.title || defaultProduct.title;
  const price = product?.price || defaultProduct.price;
  // const productId = product?.id || defaultProduct.id; // برای استفاده در لینک

  return (
    /*
    ========================================
    3️⃣ کارت اصلی محصول
    ========================================
    کل کارت داخل تگ <a> قرار گرفته تا
    کارت قابل کلیک باشد.

    در آینده این لینک می‌تواند با
    React Router به صفحه محصول
    یا صفحه نتایج متصل شود.
    (در اینجا از یک href ثابت یا href محصول استفاده می‌شود)
    */
    // <a className="product-card" href={`/products/${productId}`}>
    <a className="product-card" href="#"> {/* فعلا href ثابت است */}
      {/*
      ========================================
      4️⃣ بخش تصویر محصول
      ========================================
      این بخش تصویر محصول را نمایش می‌دهد.

      object-fit در CSS باعث می‌شود
      تصویر بدون کش آمدن داخل باکس
      قرار بگیرد.
      */}
      <div className="product-card__image">
        <img
          src={imageUrl} // استفاده از URL تصویر محصول
          alt={title}     // استفاده از عنوان محصول به عنوان alt text
        />
      </div>

      {/*
      ========================================
      5️⃣ عنوان محصول
      ========================================
      نام محصول در این قسمت نمایش داده می‌شود.

      این مقدار از props دریافت خواهد شد.
      */}
      <div className="product-card__title">
        {title} {/* نمایش عنوان محصول */}
      </div>

      {/*
      ========================================
      6️⃣ قیمت محصول
      ========================================
      قیمت محصول در پایین کارت نمایش داده می‌شود.

      رنگ قرمز و اندازه فونت
      در فایل SCSS کنترل می‌شود.
      */}
      <div className="product-card__price">
        {price} {/* نمایش قیمت محصول */}
      </div>
    </a>
  );
}
